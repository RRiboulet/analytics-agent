"""Synthesis-stage support (M7.3): evidence grounding and checking.

The report is generated by the model, but shipping it is gated by a
deterministic groundedness check outside the LLM path (PLAN M7.3): every
number appearing in the report text must match some numeric value in the
evidence result sets or in the original management request. A violation
means the report is not grounded in executed queries -- the run fails and
the report is never returned (never ship a fabricated report).

Strictness notes (deliberate, matching the hardened M7.3 contract):

* Only numeric cells ground numbers. Booleans are excluded (they are a
  separate type in the judges), and string cells -- including ISO-8601
  timestamps -- are never scanned for digits, so a report cannot ground a
  number in something that merely *contains* digits.
* Matching is strict floating-point exactness: 1e-6 relative tolerance,
  used only to absorb JSON/float representation noise. There is no
  proportional rounding exemption and no absolute +/-10 floor; numbers that
  must appear differentially should be returned by SQL.
* US/JSON numeric formatting is assumed: thousands separators are commas and
  the decimal point is a dot. Scientific notation is accepted.
* Numbers already present in the original management request are inputs,
  not claims: the manager supplied them, so a report echoing a time window
  ("2018"), threshold or identifier is not fabricating a measurement and
  needs no evidence existence proof. Sub-question text is manager-generated
  prose and is NOT exempt, because it can be used to smuggle a fabricated
  number into the allowed set.
* SQL text, analyst answers, derived ratios/percentages, and filter
  constants never ground a number unless the SQL returns that number in a row.
"""

import json
import math
import re
from decimal import Decimal

from app.manager.evidence import EvidenceRecord

# Numbers in prose: optional sign, US-format digits (with comma thousands
# separators or an ungrouped run), optional decimal part, and an optional
# scientific exponent. Parentheses/words boundaries are handled by the
# leading lookbehind so identifiers such as R2D2 or v1.2.3 are not treated
# as number sequences, while a sentence-ending "1." still extracts 1.
_NUMBER = re.compile(
    r"(?<![\w.])[-\u2212]?(?:\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?|\.\d+)(?:[eE][+-]?\d+)?(?!\d)"
)

# Strict floating-point exactness window. This is only a representation
# tolerance; it is intentionally not a licence to round prose numbers.
GROUNDEDNESS_RELATIVE_TOLERANCE = 1e-6


_ISO_DATE_LABEL = re.compile(r"(?:19|20)\d{2}-\d{1,2}(?:-\d{1,2})?")


def _iso_date_spans(text: str) -> list[tuple[int, int]]:
    return [(m.start(), m.end()) for m in _ISO_DATE_LABEL.finditer(text)]


def extract_report_numbers(report: str) -> list[float]:
    """Extract the numeric values mentioned in a report text.

    Thousands separators are stripped ("1,234.56" -> 1234.56). Duplicates are
    kept: the groundedness check is existential per extracted number.
    """
    values: list[float] = []
    for match in _NUMBER.finditer(report):
        # Components of an ISO date/month label such as "2018-04" or
        # "2018-04-07" are labels, not measurements. Skip the candidate only
        # when it lies inside one of those full label shapes; ordinary ranges
        # such as "1-3" are left strictly grounded.
        if any(
            start <= match.start() and match.end() <= end for start, end in _iso_date_spans(report)
        ):
            continue
        match_text = match.group(0)
        negative = match_text[0] in ("-", "\u2212", "\u2013")
        cleaned = match_text.lstrip("-\u2212\u2013").replace(",", "")
        try:
            value = float(cleaned)
        except (TypeError, ValueError, OverflowError):
            continue
        # Keep +/- infinity on the prose side so it must ground against finite
        # evidence and therefore fails; NaN is not a number and is discarded.
        if math.isnan(value):
            continue
        values.append(-value if negative else value)
    return values


def collect_evidence_values(evidence: list[EvidenceRecord]) -> list[float]:
    """Collect every numeric cell value from the evidence result sets."""
    values: list[float] = []
    for record in evidence:
        for row in record.rows or []:
            for cell in row.values():
                if isinstance(cell, bool) or not isinstance(cell, int | float | Decimal):
                    continue
                numeric = float(cell)
                if not math.isfinite(numeric):
                    continue
                values.append(numeric)
    return values


def _mask_evidence_strings(report: str, evidence: list[EvidenceRecord]) -> str:
    """Replace evidence string cells with a digit-free placeholder.

    Identifiers and labels must not contribute their digits to the groundedness
    scan, even when they appear verbatim in a report.
    """
    masked = report
    for record in evidence:
        for row in record.rows or []:
            for cell in row.values():
                if isinstance(cell, str) and cell:
                    masked = masked.replace(cell, " [value] ")
    return masked


def _number_matches(value: float, number: float) -> bool:
    """True when a report ``number`` can be grounded in one evidence ``value``.

    Strict matching: ``number`` must lie within 1e-6 relative to
    ``max(1, abs(value))``. Opposite signs and values more than that tiny
    floating-point window apart are rejected.
    """
    if not math.isfinite(value) or not math.isfinite(number):
        return False
    base = max(1.0, abs(value))
    return abs(number - value) <= GROUNDEDNESS_RELATIVE_TOLERANCE * base


def groundedness_violation(
    report: str, evidence: list[EvidenceRecord], task: str = ""
) -> str | None:
    """Return a violation message if the report is not fully grounded.

    A report without numbers is trivially grounded. Every number extracted
    from the report must match at least one evidence value within strict
    floating-point exactness, or one number already present in the original
    management request. Those request numbers are inputs, not claims.
    Numbers originating only from manager-generated sub-questions, SQL text
    or analyst answers do not ground a claim.
    """
    values = collect_evidence_values(evidence)
    values += extract_report_numbers(task)
    for number in extract_report_numbers(_mask_evidence_strings(report, evidence)):
        if not any(_number_matches(value, number) for value in values):
            return (
                f"Report number {number} does not appear in any evidence result set "
                f"or task context (groundedness violation)."
            )
    return None


def format_evidence(evidence: list[EvidenceRecord]) -> str:
    """Render the evidence records as the synthesis prompt's grounding text."""
    blocks: list[str] = []
    for record in evidence:
        label = (
            f"Follow-up question {record.sub_index}"
            if record.is_follow_up
            else f"Sub-question {record.sub_index}"
        )
        lines = [f"{label}: {record.sub_question}"]
        if record.error:
            lines.append(f"Status: FAILED — {record.error}")
        else:
            lines.append(f"Status: {record.status}")
            lines.append(f"SQL executed: {record.sql}")
            lines.append(f"Result rows: {json.dumps(record.rows or [], default=str)}")
            if record.answer:
                lines.append(f"Analyst answer: {record.answer}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks)
